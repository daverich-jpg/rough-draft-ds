// Builds every token output from design-tokens/source.mjs:
//   design-tokens/tokens.json          W3C Design Tokens (DTCG) format
//   design-tokens/build/tokens.css     CSS custom properties, light + dark
//   design-tokens/build/theme.css      Tailwind v4 @theme mapping
//   design-tokens/build/tailwind.config.js  Tailwind v3 preset (same tokens)
//   design-tokens/build/tokens.ts      typed JS export for runtime use
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hexToOklch, oklchToHex, fmtOklch } from './color.mjs';
import * as S from '../design-tokens/source.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (p, s) => {
  mkdirSync(dirname(join(root, p)), { recursive: true });
  writeFileSync(join(root, p), s);
  console.log('  wrote', p);
};
const P = 'rd';

// ── 1. Generate scales ───────────────────────────────────────────────────────
function parseSeed(seed) {
  if (seed.startsWith('#')) return hexToOklch(seed);
  const [l, c, h] = seed.match(/[\d.]+/g).map(Number);
  return { l, c, h };
}

const scales = {};
for (const [name, def] of Object.entries(S.SCALES)) {
  const seed = parseSeed(def.seed);
  scales[name] = {};
  S.STEPS.forEach((step, i) => {
    const pin = def.pins?.[step];
    if (pin) {
      scales[name][step] = { hex: pin, oklch: hexToOklch(pin), pinned: true };
      return;
    }
    const t = i / (S.STEPS.length - 1);
    // shortest arc around the hue wheel (355° → 0° must not pass through cyan)
    let dh = def.hue[1] - def.hue[0];
    if (dh > 180) dh -= 360;
    if (dh < -180) dh += 360;
    const h = (def.hue[0] + dh * t + 360) % 360;
    const c = def.absoluteC ? def.absoluteC[i] : seed.c * def.C[i];
    const target = { l: def.L[i], c, h };
    const hex = oklchToHex(target);
    scales[name][step] = { hex, oklch: hexToOklch(hex), pinned: false };
  });
}

const resolve = (ref) => {
  if (ref in S.STATIC_COLORS) return S.STATIC_COLORS[ref].value;
  const [scale, step] = ref.split('.');
  const v = scales[scale]?.[step];
  if (!v) throw new Error(`Unknown colour ref ${ref}`);
  return v.hex;
};
const refVar = (ref) => (ref in S.STATIC_COLORS ? `var(--${P}-${ref})` : `var(--${P}-${ref.replace('.', '-')})`);

// ── 2. DTCG tokens.json ──────────────────────────────────────────────────────
const ext = (o) => ({ $extensions: { 'com.roughdraft': o } });
const dtcg = {
  $description: 'Rough Draft design tokens. Generated by scripts/build-tokens.mjs from design-tokens/source.mjs. Do not hand-edit.',
  color: {},
  theme: {},
  font: { family: {} },
  typography: {},
  space: {},
  radius: {},
  'border-width': {},
  shadow: {},
  z: {},
  duration: {},
  easing: {},
};
for (const [name, steps] of Object.entries(scales)) {
  dtcg.color[name] = { $type: 'color', $description: `${S.SCALES[name].label}: ${S.SCALES[name].role}` };
  for (const [step, v] of Object.entries(steps))
    dtcg.color[name][step] = { $value: v.hex, ...ext({ oklch: fmtOklch(v.oklch), pinned: v.pinned }) };
}
for (const [name, v] of Object.entries(S.STATIC_COLORS))
  dtcg.color[name] = { $type: 'color', $value: v.value, $description: `${v.label}: ${v.role}` };
for (const [theme, map] of Object.entries(S.SEMANTIC)) {
  dtcg.theme[theme] = { $type: 'color' };
  for (const [k, ref] of Object.entries(map)) dtcg.theme[theme][k] = { $value: `{color.${ref}}` };
}
for (const [k, v] of Object.entries(S.FONTS))
  dtcg.font.family[k] = { $type: 'fontFamily', $value: v.value.split(',').map((s) => s.trim().replace(/'/g, '')), $description: v.role };
for (const [k, v] of Object.entries(S.TYPE_SCALE))
  dtcg.typography[k] = {
    $type: 'typography',
    $value: { fontFamily: `{font.family.${v.font}}`, fontSize: v.size, fontWeight: v.weight, lineHeight: Number(v.lh), letterSpacing: v.ls },
    $description: v.use,
    ...ext({ note: 'fontSize is a CSS clamp() for fluid sizing; tools without clamp support should use the first argument.' }),
  };
for (const [k, v] of Object.entries(S.SPACE)) dtcg.space[k] = { $type: 'dimension', $value: `${v}px` };
for (const [k, v] of Object.entries(S.RADIUS)) dtcg.radius[k] = { $type: 'dimension', $value: v.value, $description: v.use };
for (const [k, v] of Object.entries(S.BORDER)) dtcg['border-width'][k] = { $type: 'dimension', $value: v };
for (const [k, v] of Object.entries(S.SHADOW)) {
  const [x = '0', y = '0', blur = '0', spread = '0'] = v.split(' ');
  dtcg.shadow[k] = { $type: 'shadow', $value: { color: '{theme.light.shadow}', offsetX: x, offsetY: y, blur, spread } };
}
for (const [k, v] of Object.entries(S.Z)) dtcg.z[k] = { $type: 'number', $value: v };
for (const [k, v] of Object.entries(S.DURATION)) dtcg.duration[k] = { $type: 'duration', $value: v.value, $description: v.use };
for (const [k, v] of Object.entries(S.EASING)) {
  const cb = v.value.match(/cubic-bezier\(([^)]+)\)/);
  dtcg.easing[k] = cb
    ? { $type: 'cubicBezier', $value: cb[1].split(',').map(Number), $description: v.use }
    : { $type: 'string', $value: v.value, $description: `${v.use} (CSS linear() spring; no DTCG equivalent)` };
}
out('design-tokens/tokens.json', JSON.stringify(dtcg, null, 2) + '\n');

// ── 3. CSS custom properties ─────────────────────────────────────────────────
const L = [];
L.push('/* Rough Draft tokens. Generated by scripts/build-tokens.mjs. Do not edit. */', '');
L.push(':root {');
L.push('  /* primitives */');
for (const [name, steps] of Object.entries(scales))
  for (const [step, v] of Object.entries(steps)) L.push(`  --${P}-${name}-${step}: ${v.hex}; /* ${fmtOklch(v.oklch)}${v.pinned ? ' (pinned)' : ''} */`);
for (const [name, v] of Object.entries(S.STATIC_COLORS)) L.push(`  --${P}-${name}: ${v.value};`);
L.push('', '  /* type */');
for (const [k, v] of Object.entries(S.FONTS)) L.push(`  --${P}-font-${k}: ${v.value};`);
for (const [k, v] of Object.entries(S.TYPE_SCALE)) {
  L.push(`  --${P}-text-${k}: ${v.size};`);
  L.push(`  --${P}-text-${k}-lh: ${v.lh};`);
  L.push(`  --${P}-text-${k}-ls: ${v.ls};`);
}
L.push('', '  /* space (4px base) */');
for (const [k, v] of Object.entries(S.SPACE)) L.push(`  --${P}-space-${String(k).replace('.', '_')}: ${v / 16}rem;`);
L.push('', '  /* radius */');
for (const [k, v] of Object.entries(S.RADIUS)) L.push(`  --${P}-radius-${k}: ${v.value};`);
L.push('', '  /* borders */');
for (const [k, v] of Object.entries(S.BORDER)) L.push(`  --${P}-border-${k}: ${v};`);
L.push('', '  /* sticker shadows (hard offset, colour follows theme) */');
for (const [k, v] of Object.entries(S.SHADOW)) L.push(`  --${P}-shadow-${k}: ${k === 'none' ? v : `${v} var(--${P}-shadow)`};`);
L.push('', '  /* z-index */');
for (const [k, v] of Object.entries(S.Z)) L.push(`  --${P}-z-${k}: ${v};`);
L.push('', '  /* motion */');
for (const [k, v] of Object.entries(S.DURATION)) L.push(`  --${P}-duration-${k}: ${v.value};`);
for (const [k, v] of Object.entries(S.EASING)) L.push(`  --${P}-ease-${k}: ${v.value};`);
L.push('}', '');

const themeBlock = (sel, map) => {
  L.push(`${sel} {`);
  for (const [k, ref] of Object.entries(map)) L.push(`  --${P}-${k}: ${refVar(ref)};`);
  L.push('}', '');
};
themeBlock(':root,\n[data-theme="light"]', S.SEMANTIC.light);
L.push(':root,\n[data-theme="light"] { color-scheme: light; }', '');
themeBlock('[data-theme="dark"]', S.SEMANTIC.dark);
L.push('[data-theme="dark"] { color-scheme: dark; }', '');
L.push('@media (prefers-color-scheme: dark) {');
L.push('  :root:not([data-theme="light"]) {');
L.push('    color-scheme: dark;');
for (const [k, ref] of Object.entries(S.SEMANTIC.dark)) L.push(`    --${P}-${k}: ${refVar(ref)};`);
L.push('  }', '}', '');
L.push('/* Reduced motion: movement collapses to quick fades. Opt-in override via data-motion="reduced". */');
const reduced = ['delight', 'celebrate', 'slow'].map((k) => `--${P}-duration-${k}: 160ms;`).join(' ');
L.push(`@media (prefers-reduced-motion: reduce) { :root:not([data-motion="full"]) { ${reduced} --${P}-ease-spring: ease-out; --${P}-ease-slap: ease-out; } }`);
L.push(`[data-motion="reduced"] { ${reduced} --${P}-ease-spring: ease-out; --${P}-ease-slap: ease-out; }`, '');
out('design-tokens/build/tokens.css', L.join('\n'));

// ── 4. Tailwind v4 theme ─────────────────────────────────────────────────────
const T = [];
T.push('/* Rough Draft → Tailwind v4. Generated. Import after `@import "tailwindcss";` */');
T.push('@theme inline {');
T.push('  /* tokens only: Tailwind defaults are switched off so off-brand values cannot sneak in */');
T.push('  --color-*: initial;', '  --font-*: initial;', '  --radius-*: initial;', '  --shadow-*: initial;', '  --text-*: initial;', '  --ease-*: initial;');
T.push('  --color-transparent: transparent;', '  --color-current: currentColor;');
for (const [name, steps] of Object.entries(scales)) for (const step of Object.keys(steps)) T.push(`  --color-${name}-${step}: var(--${P}-${name}-${step});`);
for (const name of Object.keys(S.STATIC_COLORS)) T.push(`  --color-${name}: var(--${P}-${name});`);
for (const k of Object.keys(S.SEMANTIC.light)) T.push(`  --color-${k}: var(--${P}-${k});`);
for (const k of Object.keys(S.FONTS)) T.push(`  --font-${k}: var(--${P}-font-${k});`);
for (const k of Object.keys(S.TYPE_SCALE)) {
  T.push(`  --text-${k}: var(--${P}-text-${k});`);
  T.push(`  --text-${k}--line-height: var(--${P}-text-${k}-lh);`);
  T.push(`  --text-${k}--letter-spacing: var(--${P}-text-${k}-ls);`);
}
T.push('  --spacing: 0.25rem;');
for (const k of Object.keys(S.RADIUS)) T.push(`  --radius-${k}: var(--${P}-radius-${k});`);
for (const k of Object.keys(S.SHADOW)) T.push(`  --shadow-sticker-${k}: var(--${P}-shadow-${k});`);
for (const k of Object.keys(S.EASING)) T.push(`  --ease-${k}: var(--${P}-ease-${k});`);
T.push('}', '');
out('design-tokens/build/theme.css', T.join('\n'));

// ── 5. Tailwind v3 preset ────────────────────────────────────────────────────
const v3colors = {};
for (const [name, steps] of Object.entries(scales)) {
  v3colors[name] = {};
  for (const step of Object.keys(steps)) v3colors[name][step] = `var(--${P}-${name}-${step})`;
}
for (const name of Object.keys(S.STATIC_COLORS)) v3colors[name] = `var(--${P}-${name})`;
for (const k of Object.keys(S.SEMANTIC.light)) v3colors[k] = `var(--${P}-${k})`;
const v3 = {
  theme: {
    colors: { transparent: 'transparent', current: 'currentColor', ...v3colors },
    fontFamily: Object.fromEntries(Object.keys(S.FONTS).map((k) => [k, `var(--${P}-font-${k})`])),
    fontSize: Object.fromEntries(
      Object.keys(S.TYPE_SCALE).map((k) => [k, [`var(--${P}-text-${k})`, { lineHeight: `var(--${P}-text-${k}-lh)`, letterSpacing: `var(--${P}-text-${k}-ls)` }]]),
    ),
    borderRadius: Object.fromEntries(Object.keys(S.RADIUS).map((k) => [k, `var(--${P}-radius-${k})`])),
    boxShadow: Object.fromEntries(Object.keys(S.SHADOW).map((k) => [`sticker-${k}`, `var(--${P}-shadow-${k})`])),
    extend: {
      transitionTimingFunction: Object.fromEntries(Object.keys(S.EASING).map((k) => [k, `var(--${P}-ease-${k})`])),
      transitionDuration: Object.fromEntries(Object.keys(S.DURATION).map((k) => [k, `var(--${P}-duration-${k})`])),
      zIndex: Object.fromEntries(Object.entries(S.Z).map(([k, v]) => [k, String(v)])),
    },
  },
};
out('design-tokens/build/tailwind.config.js', `/** Rough Draft Tailwind v3 preset. Generated. Requires build/tokens.css on the page. */\nexport default ${JSON.stringify(v3, null, 2)};\n`);

// ── 6. Typed JS export ───────────────────────────────────────────────────────
const js = {
  scales: Object.fromEntries(
    Object.entries(scales).map(([n, steps]) => [
      n,
      { label: S.SCALES[n].label, role: S.SCALES[n].role, steps: Object.fromEntries(Object.entries(steps).map(([s, v]) => [s, { hex: v.hex, oklch: fmtOklch(v.oklch), pinned: v.pinned }])) },
    ]),
  ),
  semantic: Object.fromEntries(
    Object.entries(S.SEMANTIC).map(([t, map]) => [t, Object.fromEntries(Object.entries(map).map(([k, ref]) => [k, { ref, hex: resolve(ref) }]))]),
  ),
  contrastPairs: S.CONTRAST_PAIRS,
  typeScale: S.TYPE_SCALE,
  fonts: S.FONTS,
  space: S.SPACE,
  radius: S.RADIUS,
  shadow: S.SHADOW,
  duration: S.DURATION,
  easing: S.EASING,
};
out('design-tokens/build/tokens.ts', `// Generated by scripts/build-tokens.mjs. Do not edit.\nexport const tokens = ${JSON.stringify(js, null, 2)} as const;\nexport type SemanticToken = keyof typeof tokens.semantic.light;\n`);
console.log('tokens built.');
