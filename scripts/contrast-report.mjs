// Writes foundations/contrast-matrix.md and exits non-zero if any semantic text
// pairing drops below WCAG AA (4.5:1) or any UI pairing below 3:1.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrast, grade } from './color.mjs';
import { SEMANTIC, CONTRAST_PAIRS } from '../design-tokens/source.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design-tokens/tokens.json'), 'utf8'));
const hexOf = (ref) => {
  const [a, b] = ref.split('.');
  return b ? tokens.color[a][b].$value : tokens.color[a].$value;
};

const md = [];
md.push('# Contrast matrix', '');
md.push('Generated by `npm run contrast` (scripts/contrast-report.mjs). Every pairing below is checked on each build; the build fails if a text pair drops under 4.5:1 or a UI pair under 3:1.', '');
md.push('Legend: **AAA** ≥ 7 · **AA** ≥ 4.5 · **large only** 3 to 4.5 (≥24px, or ≥18.66px bold) · **AA (UI)** ≥ 3 for borders, icons and focus rings · **FAIL**.', '');

// 1. Core brand matrix
const core = [
  ['Sunshine', '#FFD86C'],
  ['Paper White', '#FFFFFF'],
  ['Cream', '#FFEFC4'],
  ['Spark Lime', '#B6F500'],
  ['Deep Brown', '#433100'],
  ['Midnight Navy', '#090446'],
  ['Ink', '#1E1B16'],
];
md.push('## 1. Core palette, every pairing', '', 'Rows are the text colour, columns are the background.', '');
md.push('| text ↓ / bg → | ' + core.map(([n]) => n).join(' | ') + ' |');
md.push('|' + '---|'.repeat(core.length + 1));
for (const [fn, fh] of core) {
  const cells = core.map(([, bh]) => {
    if (fh === bh) return '·';
    const r = contrast(fh, bh);
    const g = grade(r);
    return `${r.toFixed(2)} ${g === 'FAIL' ? '❌' : g === 'large only' ? '⚠️' : '✅'}`;
  });
  md.push(`| **${fn}** | ${cells.join(' | ')} |`);
}
md.push('');
md.push('### Banned text pairings (decorative fills only)', '');
md.push('- **Sunshine on Paper White (1.37:1): unusable for text.** Also no yellow icons on white.');
md.push('- **Sunshine on Cream (1.15:1)**, **Spark Lime on Cream / White / Sunshine**: same rule.');
md.push('- **Brown on Navy / Ink on Navy**: both dark. Never pair.');
md.push('- Lime is a *fill*. Text placed on lime is always Ink.', '');

// 2. Semantic pairs per theme
let failures = 0;
for (const theme of Object.keys(SEMANTIC)) {
  md.push(`## 2. Semantic pairs: ${theme} theme`, '');
  md.push('| foreground | background | fg | bg | ratio | grade |');
  md.push('|---|---|---|---|---|---|');
  for (const [fg, bg, kind] of CONTRAST_PAIRS) {
    const fh = hexOf(SEMANTIC[theme][fg]);
    const bh = hexOf(SEMANTIC[theme][bg]);
    let r = contrast(fh, bh);
    let label = fg;
    if (kind === 'focus') {
      const halo = contrast(hexOf(SEMANTIC[theme]['focus-halo']), bh);
      if (halo > r) { r = halo; label = 'focus-halo'; }
    }
    const g = grade(r, { ui: kind !== 'text' });
    const isPlaceholder = fg === 'text-placeholder';
    const fail = kind !== 'text' ? r < 3 : r < 4.5;
    if (fail) failures++;
    md.push(`| \`${label}\` | \`${bg}\` | ${label === fg ? fh : hexOf(SEMANTIC[theme][label])} | ${bh} | ${r.toFixed(2)} | ${fail ? '❌ ' : ''}${g}${isPlaceholder ? ' (placeholder held to body AA)' : ''} |`);
  }
  md.push('');
}
writeFileSync(join(root, 'foundations/contrast-matrix.md'), md.join('\n') + '\n');
console.log('  wrote foundations/contrast-matrix.md');
if (failures) {
  console.error(`✗ ${failures} semantic pairing(s) below threshold. See foundations/contrast-matrix.md`);
  process.exit(1);
}
console.log('✓ all semantic pairings pass.');
